// Writes templates/known-versions.json: the hash of each set-up template that every earlier release shipped,
// read from the v* release tags. Hosts set up before versions were recorded have no marker in their files, so
// the upgrade review matches their files against these hashes to tell an unedited part from an edited one.
//
// Run it with `npm run known-versions` before tagging a release. The release workflow runs it again from the
// tags and fails when the committed file differs. Tags at HEAD are left out, so the tag being released never
// changes the result. Needs the tags locally: in CI, check out with fetch-depth: 0.
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { workflowWithTests } from "../dist/init.js";
import { knownSetupVersionsFrom } from "../dist/setup-versions.js";

const root = new URL("..", import.meta.url);
const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 64 * 1024 * 1024 });
const show = (tag, path) => {
  try {
    return git("show", `${tag}:${path}`);
  } catch {
    return undefined; // The file did not exist at that tag.
  }
};

const atHead = new Set(git("tag", "--points-at", "HEAD").split("\n").filter(Boolean));
const tags = git("tag", "--list", "v*").split("\n").filter(tag => /^v\d+\.\d+\.\d+$/.test(tag) && !atHead.has(tag));

// The test folders init may add to the workflow, so a host's workflow with --tests matches too.
const testFolders = ["test", "tests", "__tests__"];
const templates = [];
for (const tag of tags) {
  const version = tag.slice(1);
  for (const name of ["templates/AGENTS.md", "templates/AGENTS-skill.md"]) {
    const text = show(tag, name);
    if (text !== undefined) templates.push({ part: "agents", version, text });
  }
  const guide = show(tag, "docs/story-map.md");
  if (guide !== undefined) templates.push({ part: "guide", version, text: guide });
  const workflow = show(tag, "templates/story-map-ci.yml");
  if (workflow !== undefined) {
    for (const folder of [undefined, ...testFolders]) templates.push({ part: "workflow", version, text: workflowWithTests(workflow, folder) });
  }
}

const known = knownSetupVersionsFrom(templates);
const output = `${JSON.stringify({ $comment: "Generated by scripts/known-versions.mjs from the release tags. Do not edit.", ...known }, null, 2)}\n`;
const path = new URL("templates/known-versions.json", root);
const previous = await readFile(path, "utf8").catch(() => undefined);
if (previous === output) {
  console.log(`templates/known-versions.json is up to date (${tags.length} tags).`);
} else {
  await writeFile(path, output);
  console.log(`Wrote templates/known-versions.json from ${tags.length} tags.`);
}
