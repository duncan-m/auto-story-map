// Writes src/version.ts from package.json, so the board can show which version is running.
// Runs before `tsc`. The output is generated, so it is not committed.
import { readFile, writeFile } from "node:fs/promises";

const pkg = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const repositoryUrl = pkg.repository.url.replace(/^git\+/, "").replace(/\.git$/, "");
await writeFile(new URL("../src/version.ts", import.meta.url), `// Generated by scripts/write-version.mjs from package.json. Do not edit.
/** The installed version of embedded-story-map. */
export const storyMapVersion = ${JSON.stringify(pkg.version)};
/** The library's source repository. */
export const storyMapRepositoryUrl = ${JSON.stringify(repositoryUrl)};
`);
