// Writes src/version.ts from package.json and the current git commit, so the board can show which version is running,
// its licence and its author. Runs before `tsc`. The output is generated, so it is not committed.
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";

const pkg = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const repositoryUrl = pkg.repository.url.replace(/^git\+/, "").replace(/\.git$/, "");
// npm accepts an author object or a "Name <email> (url)" string. Only the name and URL are shown.
const author = typeof pkg.author === "string"
  ? { name: pkg.author.replace(/\s*[<(].*$/, ""), url: /\(([^)]+)\)/.exec(pkg.author)?.[1] }
  : { name: pkg.author.name, url: pkg.author.url };
// The short hash of the commit being built, so two builds of the same version can be told apart.
// Builds outside a git checkout, such as from a tarball, have none.
function commitHash() {
  try {
    return execFileSync("git", ["rev-parse", "--short=7", "HEAD"], { cwd: new URL("..", import.meta.url), encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() || undefined;
  } catch {
    return undefined;
  }
}
const commit = commitHash();
await writeFile(new URL("../src/version.ts", import.meta.url), `// Generated by scripts/write-version.mjs from package.json. Do not edit.
/** The installed version of auto-story-map. */
export const storyMapVersion = ${JSON.stringify(pkg.version)};
/** The short hash of the commit this build came from, when it was built from a git checkout. */
export const storyMapCommit: string | undefined = ${JSON.stringify(commit)};
/** The library's source repository. */
export const storyMapRepositoryUrl = ${JSON.stringify(repositoryUrl)};
/** The library's SPDX licence identifier. */
export const storyMapLicense = ${JSON.stringify(pkg.license)};
/** The library's author. */
export const storyMapAuthor: { name: string; url?: string } = ${JSON.stringify(author)};
`);
